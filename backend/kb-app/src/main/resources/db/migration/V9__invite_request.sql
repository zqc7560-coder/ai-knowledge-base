-- V9: M10.5 邀请链接 + 入伙申请审批
CREATE TABLE IF NOT EXISTS kb_invites (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  kb_id BIGINT NOT NULL,
  token CHAR(24) NOT NULL COMMENT 'SecureRandom hex，EDIT 者生成',
  permission VARCHAR(8) NOT NULL DEFAULT 'READ' COMMENT '加入后授予的权限档位',
  max_uses INT NOT NULL DEFAULT 1,
  used INT NOT NULL DEFAULT 0,
  expires_at DATETIME NOT NULL,
  created_by BIGINT NOT NULL,
  revoked TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uk_token (token), KEY idx_kb (kb_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='知识库邀请链接(M10.5)';

CREATE TABLE IF NOT EXISTS kb_requests (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  kb_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  state VARCHAR(8) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING|APPROVED|REJECTED',
  decided_by BIGINT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  decided_at DATETIME NULL,
  UNIQUE KEY uk_kb_user (kb_id, user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='入伙申请(M10.5)';
